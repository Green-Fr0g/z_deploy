import os

from setuptools import find_packages, setup

package_name = 'robot_mujoco_sim'

setup(
    name=package_name,
    version='0.1.0',
    packages=find_packages(),
    data_files=[
        ('share/ament_index/resource_index/packages', ['resource/' + package_name]),
        ('share/' + package_name, ['package.xml']),
        ('share/' + package_name + '/config', ['config/sim.yaml']),
        ('lib/' + package_name, ['scripts/robot_mujoco_sim']),
    ] + [
        ('share/' + package_name + '/' + os.path.dirname(path), [path])
        for root, _, files in os.walk('robots_model')
        for path in (os.path.join(root, filename) for filename in files)
    ],
    # ROS Humble ships binary extensions built against NumPy 1.x.
    install_requires=['setuptools', 'PyYAML', 'numpy<1.25', 'mujoco', 'mjviser'],
    zip_safe=True,
    # The launcher is installed as package data so it remains an
    # environment-based script instead of being regenerated by setuptools
    # with a /usr/bin/python3 shebang.
)
